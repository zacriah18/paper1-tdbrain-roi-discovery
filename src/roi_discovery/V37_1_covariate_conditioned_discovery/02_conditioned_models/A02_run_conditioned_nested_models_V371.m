%% Compare intercept, nuisance, QC, neural and combined models on locked folds.
clear;clc;root=fileparts(fileparts(mfilename('fullpath')));addpath(fullfile(root,'lib'));
cfg=v371_setup();out=fullfile(cfg.output_root,'02_conditioned_models');if ~exist(out,'dir'),mkdir(out);end
D=load(fullfile(cfg.project_root,'derivatives','V37_DCM_concordant_ROI_discovery', ...
    '03_participant_features','A03_participant_spectral_landscapes.mat'),'dataset');dataset=D.dataset;
F=load(fullfile(cfg.output_root,'01_folds','A01_locked_nested_folds.mat'),'folds');folds=F.folds;
if ~isequal(string(dataset.participants.subject_id),folds.subject_id)
    error('V371:FoldJoin','Dataset order differs from locked fold manifest.');
end
y=double(string(dataset.participants.group)=="MDD");
result=v371_run_conditioned_nested(dataset,cfg,y,folds,true);

prediction=dataset.participants(:,{'subject_id','group','age','sex','age_band','condition_availability'});
for i=1:numel(result.model_names),prediction.(result.model_names(i)+"_probability")=result.probability(:,i);end
writetable(prediction,fullfile(out,'A02_out_of_fold_predictions.csv'));
writetable(result.fold_results,fullfile(out,'A02_outer_fold_comparison.csv'));

rows=table();
for i=1:numel(result.model_names)
    name=result.model_names(i);m=result.metrics.(name);if isempty(m),continue;end
    row=table(name,m.AUC,m.log_loss,m.Brier,m.balanced_accuracy,m.sensitivity,m.specificity, ...
        m.calibration_intercept,m.calibration_slope, ...
        'VariableNames',{'model','AUC','log_loss','Brier','balanced_accuracy','sensitivity', ...
        'specificity','calibration_intercept','calibration_slope'});rows=[rows;row]; %#ok<AGROW>
end
writetable(rows,fullfile(out,'A02_model_performance.csv'));
increment=table(result.primary_incremental_log_loss,result.secondary_incremental_AUC,0, ...
    'VariableNames',{'incremental_log_loss_combined_vs_demographic', ...
    'incremental_AUC_combined_vs_demographic','validation_participants_read'});
writetable(increment,fullfile(out,'A02_primary_incremental_performance.csv'));
patch=table(result.patch_id,result.eligible_count,result.combined_selection_count, ...
    result.combined_selection_frequency,result.combined_mean_coefficient_magnitude, ...
    result.neural_selection_count,result.neural_selection_frequency, ...
    result.neural_mean_coefficient_magnitude, ...
    'VariableNames',{'patch_id','eligible_outer_folds','combined_selected_outer_folds', ...
    'combined_selection_frequency','combined_mean_coefficient_magnitude', ...
    'neural_selected_outer_folds','neural_selection_frequency','neural_mean_coefficient_magnitude'});
writetable(patch,fullfile(out,'A02_conditioned_patch_stability.csv'));
save(fullfile(out,'A02_conditioned_nested_models.mat'),'result','dataset','folds','cfg','-v7.3');
fprintf('Combined AUC %.3f vs demographic %.3f; incremental log loss %.4f; validation read=0.\n', ...
    result.metrics.combined.AUC,result.metrics.demographic.AUC,result.primary_incremental_log_loss);
