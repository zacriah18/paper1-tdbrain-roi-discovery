%% Apply the prespecified pre-DCM gate after A14 and A16 complete.
clear;clc;root=fileparts(fileparts(mfilename('fullpath')));addpath(fullfile(root,'lib'));
cfg=v371_setup();out=fullfile(cfg.output_root,'07_pre_DCM_gate');
required={fullfile(out,'A14_EO_sensor_ocular_proxy_summary.csv'), ...
    fullfile(out,'A16_recording_joint_observability.csv'),fullfile(out,'A16_recording_node_visibility.csv'), ...
    fullfile(out,'A16_recording_pair_overlap_and_CSD.csv'),fullfile(out,'A16_CSD_observability_status.csv')};
if ~all(cellfun(@(f)exist(f,'file')==2,required)),error('V371:PreDCMPending','Pre-DCM component outputs are incomplete.');end
ocular=readtable(required{1},'Delimiter',',','TextType','string');
R=readtable(required{2},'Delimiter',',','TextType','string');N=readtable(required{3},'Delimiter',',','TextType','string');
P=readtable(required{4},'Delimiter',',','TextType','string');S=readtable(required{5},'Delimiter',',','TextType','string');
conditions=["ALL";"restEC";"restEO"];condition_rows=table();
for i=1:numel(conditions)
    if conditions(i)=="ALL",x=R;else,x=R(string(R.condition)==conditions(i),:);end
    row=table(conditions(i),height(x),numel(unique(string(x.subject_id))), ...
        mean(x.numerical_noncollapse_pass),median(x.joint_effective_rank),prctile(x.joint_effective_rank,5), ...
        median(x.minimum_unique_residual_norm),prctile(x.minimum_unique_residual_norm,5), ...
        'VariableNames',{'condition','recordings','participants','noncollapse_pass_rate', ...
        'median_joint_effective_rank','p05_joint_effective_rank','median_minimum_unique_residual', ...
        'p05_minimum_unique_residual'});
    condition_rows=[condition_rows;row]; %#ok<AGROW>
end
writetable(condition_rows,fullfile(out,'A17_condition_observability_summary.csv'));

node_rows=table();
for condition=conditions'
    for node=1:4
        x=N(N.node==node,:);if condition~="ALL",x=x(string(x.condition)==condition,:);end
        row=table(condition,node,x.patch_id(1),height(x),median(x.channel_mode_visibility), ...
            median(x.projected_effective_rank),prctile(x.projected_effective_rank,5), ...
            median(x.CSD_energy_fraction),median(x.unique_residual_norm),prctile(x.unique_residual_norm,5), ...
            median(x.unique_CSD_energy_fraction), ...
            'VariableNames',{'condition','node','patch_id','recordings','median_SPM_scaled_projection_gain', ...
            'median_projected_effective_rank','p05_projected_effective_rank','median_CSD_energy_fraction', ...
            'median_unique_residual_norm','p05_unique_residual_norm','median_unique_CSD_energy_fraction'});
        node_rows=[node_rows;row]; %#ok<AGROW>
    end
end
writetable(node_rows,fullfile(out,'A17_node_observability_summary.csv'));

pair_rows=table();pairs=unique(P(:,{'node_i','node_j'}),'rows');
for condition=conditions'
    for k=1:height(pairs)
        x=P(P.node_i==pairs.node_i(k)&P.node_j==pairs.node_j(k),:);
        if condition~="ALL",x=x(string(x.condition)==condition,:);end
        row=table(condition,pairs.node_i(k),pairs.node_j(k),height(x), ...
            median(x.projected_rms_canonical_correlation),prctile(x.projected_rms_canonical_correlation,95), ...
            median(x.dominant_pattern_correlation),median(x.mean_coherence),median(x.mean_imaginary_coherence), ...
            'VariableNames',{'condition','node_i','node_j','recordings','median_regional_subspace_RMS_correlation', ...
            'p95_regional_subspace_RMS_correlation','median_dominant_pattern_correlation', ...
            'median_CSD_coherence','median_CSD_imaginary_coherence'});
        pair_rows=[pair_rows;row]; %#ok<AGROW>
    end
end
writetable(pair_rows,fullfile(out,'A17_pair_observability_summary.csv'));

condition_pass=condition_rows.noncollapse_pass_rate>=.95 & ...
    condition_rows.p05_minimum_unique_residual>.10 & condition_rows.median_joint_effective_rank>=2.5;
node_pass=all(node_rows.median_SPM_scaled_projection_gain>0 & node_rows.median_unique_CSD_energy_fraction>0);
errors=sum(string(S.status)=="ERROR");complete=height(R)==height(S)-errors&&height(R)>=186-errors;
technical_pass=all(condition_pass)&&node_pass&&errors==0&&complete;
ocular_warning=ocular.Holm_positive_frontal_polar_channels>0 || ...
    ocular.maximum_absolute_frontal_polar_source_score_correlation>=.70;
if technical_pass&&~ocular_warning,decision="PASS";elseif technical_pass,decision="QUALIFIED_PASS";else,decision="FAIL";end
gate=table(datetime('now'),decision,technical_pass,ocular_warning,height(R),errors, ...
    condition_pass(1),condition_pass(2),condition_pass(3),node_pass, ...
    "Frozen four-node feasibility only; no effective-connectivity or causal inference", ...
    'VariableNames',{'created','decision','technical_observability_pass','ocular_proxy_warning', ...
    'recordings_audited','extraction_errors','all_recordings_gate_pass','EC_gate_pass','EO_gate_pass', ...
    'all_nodes_visible_and_CSD_nonzero','scope'});
writetable(gate,fullfile(out,'A17_pre_DCM_gate_decision.csv'));
save(fullfile(out,'A17_pre_DCM_gate_results.mat'),'gate','condition_rows','node_rows','pair_rows','ocular','cfg','-v7.3');
fprintf('PRE-DCM GATE: %s; recordings=%d errors=%d EC=%d EO=%d ocular_warning=%d\n', ...
    decision,height(R),errors,condition_pass(2),condition_pass(3),ocular_warning);
