%% Discovery-only peer-set comparison and validation freeze preparation.
clear;clc;root=fileparts(fileparts(mfilename('fullpath')));addpath(fullfile(root,'lib'));
cfg=v371_setup();smoke=strcmpi(getenv('TDBRAIN_V371_PEER_SMOKE'),'true');
if smoke
    cfg.outer_repeats=1;cfg.peer_bootstrap_count=200;cfg.peer_random_sets_per_fold=2;
    out=fullfile(cfg.output_root,'05_peer_set_comparison_smoke');
else
    out=fullfile(cfg.output_root,'05_peer_set_comparison');
end
if ~exist(out,'dir'),mkdir(out);end
checkpoint=fullfile(out,'A08_peer_set_checkpoint.mat');

D=load(fullfile(cfg.project_root,'derivatives','V37_DCM_concordant_ROI_discovery', ...
    '03_participant_features','A03_participant_spectral_landscapes.mat'),'dataset');dataset=D.dataset;
P=load(fullfile(cfg.project_root,'derivatives','V37_DCM_concordant_ROI_discovery', ...
    '01_exact_IMG_patches','A01_exact_SPM_IMG_patch_universe.mat'),'patches');patches=P.patches;
F=load(fullfile(cfg.output_root,'01_folds','A01_locked_nested_folds.mat'),'folds');folds=F.folds;
if ~isequal(string(dataset.participants.subject_id),folds.subject_id)
    error('V371:FoldJoin','Dataset order differs from locked fold manifest.');
end
if dataset.n_validation_participants_read~=0||any(string(dataset.participants.assignment)~="discovery")
    error('V371:ValidationBoundary','Validation participants may not enter peer comparison.');
end
y=double(string(dataset.participants.group)=="MDD");
result=v371_run_peer_set_comparison(dataset,patches,cfg,y,folds,checkpoint);

writetable(result.performance.top_k,fullfile(out,'A08_topK_out_of_fold_performance.csv'));
writetable(result.fold_rows,fullfile(out,'A08_outer_fold_candidate_sets.csv'));
writetable(result.rule_rows,fullfile(out,'A08_regenerated_rule_comparison.csv'));
writetable(result.sensitivity_rows,fullfile(out,'A08_peer_set_sensitivity.csv'));

selection_table=struct2table(result.selection,'AsArray',true);
writetable(selection_table,fullfile(out,'A08_model_size_selection.csv'));

patch_table=patches.patch_table;
score=table(result.patch_id,result.combined_consensus_frequency,result.combined_mean_group_norm, ...
    'VariableNames',{'patch_id','combined_consensus_frequency','combined_mean_group_norm'});
score=outerjoin(score,patch_table,'Keys','patch_id','MergeKeys',true,'Type','left');
score.is_primary_frozen_roi=ismember(score.patch_id,result.final_patch_ids);
score.is_dcm_candidate_roi=ismember(score.patch_id,result.dcm_candidate_patch_ids);
score=sortrows(score,{'is_primary_frozen_roi','combined_consensus_frequency','combined_mean_group_norm'}, ...
    {'descend','descend','descend'});
writetable(score,fullfile(out,'A08_ranked_patch_candidates.csv'));
writetable(score(score.is_primary_frozen_roi,:),fullfile(out,'A08_final_primary_ROI_set.csv'));
if ~isempty(result.dcm_candidate_patch_ids)
    writetable(score(score.is_dcm_candidate_roi,:),fullfile(out,'A08_DCM_candidate_ROI_set.csv'));
end

I=result.identifiability;
ident=table(numel(result.final_patch_ids),I.pairwise_pass,I.dominant_pattern_joint_rank, ...
    I.dominant_pattern_effective_rank,I.regional_block_rank,min(I.sensor_mode_visibility), ...
    I.structural_pass,I.sensor_space_CSD_sensitivity_pending,0, ...
    'VariableNames',{'K','pairwise_pass','dominant_pattern_joint_rank', ...
    'dominant_pattern_effective_rank','regional_block_rank','minimum_sensor_mode_visibility', ...
    'structural_pass','sensor_space_CSD_sensitivity_pending','validation_participants_read'});
writetable(ident,fullfile(out,'A08_primary_identifiability_audit.csv'));
if ~isempty(result.dcm_candidate_patch_ids)
    J=result.dcm_identifiability;
    dcm_ident=table(numel(result.dcm_candidate_patch_ids),J.pairwise_pass,J.dominant_pattern_joint_rank, ...
        J.dominant_pattern_effective_rank,J.regional_block_rank,min(J.sensor_mode_visibility), ...
        J.structural_pass,J.sensor_space_CSD_sensitivity_pending,0, ...
        'VariableNames',{'K','pairwise_pass','dominant_pattern_joint_rank', ...
        'dominant_pattern_effective_rank','regional_block_rank','minimum_sensor_mode_visibility', ...
        'structural_pass','sensor_space_CSD_sensitivity_pending','validation_participants_read'});
    writetable(dcm_ident,fullfile(out,'A08_DCM_identifiability_audit.csv'));
end

manifest=local_manifest(result,dataset,patches,cfg,smoke);
manifest_json=jsonencode(manifest,'PrettyPrint',true);
manifest.sha256=local_sha256(manifest_json);
manifest_json=jsonencode(manifest,'PrettyPrint',true);
if result.validation_freeze_ready&&~smoke
    manifest_file=fullfile(out,'A08_validation_freeze_manifest.json');
else
    manifest_file=fullfile(out,'A08_validation_freeze_manifest_DRAFT.json');
end
fid=fopen(manifest_file,'w');assert(fid>0,'Unable to create manifest.');
cleanup=onCleanup(@()fclose(fid));fwrite(fid,manifest_json,'char');clear cleanup

decision=table(datetime('now'),string(cfg.peer_pipeline_version),result.validation_freeze_ready, ...
    result.selection.chosen_k,string(strjoin(string(result.final_patch_ids),';')), ...
    result.selection.incremental_log_loss,result.identifiability.structural_pass, ...
    result.identifiability.sensor_space_CSD_sensitivity_pending,0,false, ...
    'VariableNames',{'created','pipeline_version','validation_freeze_ready','chosen_K', ...
    'patch_ids','discovery_incremental_log_loss','structural_identifiability_pass', ...
    'sensor_space_CSD_sensitivity_pending','validation_participants_read','validation_access_allowed'});
writetable(decision,fullfile(out,'A08_validation_decision_log.csv'));
save(fullfile(out,'A08_peer_set_comparison.mat'),'result','cfg','manifest','-v7.3');
fprintf('PEER SET COMPARISON COMPLETE: chosen K=%d deltaLL=%.4f structural_pass=%d validation read=0.\n', ...
    result.selection.chosen_k,result.selection.incremental_log_loss,result.identifiability.structural_pass);
fprintf('Manifest: %s\n',manifest_file);

function manifest=local_manifest(result,dataset,patches,cfg,smoke)
ids=result.final_patch_ids(:);[~,loc]=ismember(ids,patches.patch_table.patch_id);
coords=[patches.patch_table.x(loc),patches.patch_table.y(loc),patches.patch_table.z(loc)];
support=cell(numel(ids),1);feature_names=strings(numel(ids)*cfg.spectral_basis_count,1);
cursor=0;
for i=1:numel(ids)
    support{i}=find(patches.membership(:,ids(i)))';
    for q=1:cfg.spectral_basis_count
        cursor=cursor+1;feature_names(cursor)=sprintf('patch_%d_spectral_coefficient_%d',ids(i),q);
    end
end
manifest=struct('status',string(local_status(result.validation_freeze_ready,smoke)), ...
    'created',string(datetime('now','Format','yyyy-MM-dd''T''HH:mm:ssXXX')), ...
    'pipeline_version',cfg.peer_pipeline_version,'discovery_participants',height(dataset.participants), ...
    'expected_validation_participants',cfg.expected_validation_participants, ...
    'validation_participants_read',0,'validation_access_allowed',false, ...
    'primary_endpoint','incremental held-out log loss: combined minus demographic model', ...
    'primary_inference','10,000 fixed-model label permutations within age-band, sex and condition-availability blocks', ...
    'secondary_endpoints',{{'AUC','Brier','balanced accuracy','sensitivity','specificity','calibration intercept','calibration slope'}}, ...
    'chosen_K',result.selection.chosen_k,'patch_ids',ids,'coordinates_mm',coords, ...
    'secondary_DCM_candidate_K',numel(result.dcm_candidate_patch_ids), ...
    'secondary_DCM_candidate_patch_ids',result.dcm_candidate_patch_ids, ...
    'exact_vertex_supports',{support},'patch_radius_mm',cfg.patch_radius_mm, ...
    'regional_spatial_modes',cfg.regional_spatial_modes,'frequency_hz',dataset.frequency_hz, ...
    'spectral_basis',result.spectral_basis,'feature_names',feature_names, ...
    'participant_normalization',dataset.primary_representation, ...
    'nuisance_names',{result.nuisance_names},'ridge_lambda',result.frozen_model.lambda, ...
    'neural_mean',result.frozen_model.neural_mean,'neural_scale',result.frozen_model.neural_scale, ...
    'nuisance_mean',result.frozen_model.nuisance_mean,'nuisance_scale',result.frozen_model.nuisance_scale, ...
    'neural_coefficients',result.frozen_model.model.beta, ...
    'nuisance_coefficients',result.frozen_model.model.gamma, ...
    'intercept',result.frozen_model.model.intercept, ...
    'demographic_coefficients',result.frozen_demographic_model.beta, ...
    'validation_fixed_permutation_count',cfg.validation_fixed_permutation_count, ...
    'validation_fixed_permutation_seed',cfg.validation_fixed_permutation_seed, ...
    'model_size_rule','smallest K within one participant-bootstrap SE of best held-out log loss', ...
    'redundancy_distance_mm',cfg.redundancy_coordinate_distance_mm, ...
    'redundancy_rms_canonical_correlation',cfg.redundancy_subspace_rms_correlation, ...
    'discovery_incremental_log_loss',result.selection.incremental_log_loss, ...
    'discovery_incremental_log_loss_95CI',result.selection.incremental_log_loss_ci, ...
    'structural_identifiability_pass',result.identifiability.structural_pass, ...
    'sensor_space_CSD_sensitivity_pending',result.identifiability.sensor_space_CSD_sensitivity_pending, ...
    'prior_validation_use_detected',exist(fullfile(cfg.project_root,'derivatives','V32_induced', ...
        '10_heldout_validation','A10_heldout_primary_results.csv'),'file')==2, ...
    'claim_tier','internal held-out confirmation for V37.1; not an untouched study-program-level external validation', ...
    'region_level_testing','one joint six-component test per ROI; Holm correction across ROIs', ...
    'individual_component_testing','exploratory only after regional confirmation', ...
    'refitting_in_validation',false,'post_access_changes_permitted',false);
end
function status=local_status(ready,smoke)
if smoke,status='SMOKE_DRAFT';elseif ready,status='FROZEN_FOR_VALIDATION';else,status='NOT_READY';end
end
function value=local_sha256(text)
md=java.security.MessageDigest.getInstance('SHA-256');md.update(uint8(unicode2native(text,'UTF-8')));
value=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2)',1,[]));
end
