function [Q,names] = v371_qc_features(dataset)
%V371_QC_FEATURES Participant-level technical negative-control features.
T=dataset.technical;
rel=double(T.split_half_spectral_correlation);
fn=double(T.filter_norm); pv=double(T.mean_posterior_variance);
epochs=double(T.good_epoch_count);
Q=[median(rel,2,'omitnan'),local_iqr(rel), ...
    median(log(max(fn,eps)),2,'omitnan'),local_iqr(log(max(fn,eps))), ...
    median(log(max(pv,eps)),2,'omitnan'),local_iqr(log(max(pv,eps))), ...
    mean(epochs,2,'omitnan'),min(epochs,[],2,'omitmissing'), ...
    double(dataset.has_paired_conditions(:))];
names={'median_split_half_reliability','IQR_split_half_reliability', ...
    'median_log_filter_norm','IQR_log_filter_norm', ...
    'median_log_posterior_variance','IQR_log_posterior_variance', ...
    'mean_good_epochs','minimum_good_epochs','paired_condition_available'};
end
function q=local_iqr(X)
q=prctile(X,75,2)-prctile(X,25,2);
end
